    /** Points "x,y" separated by whitespace. */
    private fun trace(points: String): Trace {
        val values = points.trim().split(Regex("\\s+")).map { point -> point.split(',').map { it.toFloat() } }
        return Trace(FloatArray(values.size) { values[it][0] }, FloatArray(values.size) { values[it][1] })
    }
